/**
 * The browser's look on what Firefox still draws itself: a page's dialogs
 * (alert(), confirm(), prompt(), leave-page and sign-in prompts), Firefox's
 * panels (the permission prompts it shows, the downloads and bookmark
 * panels, form autocomplete), the bars over the page, the find bar and the
 * link status bubble.
 *
 * The app describes its look in browser.json's "theme": a font, a few
 * colors for light and dark, corner radii. tools/app.ts bundles that as CSS
 * custom properties (--neeko-theme-*) at chrome://neeko-theme/content/.
 * Neeko's own sheets map them onto Firefox's styles, mostly through
 * Firefox's design tokens (--panel-*, --button-*...), so apps never style
 * Firefox's elements themselves and Neeko keeps the mapping working across
 * Firefox updates. The colors follow the color scheme (neeko.colorScheme).
 *
 * Every browser window gets it, pop-ups included. Without a theme nothing
 * changes: Firefox's own look is the fallback.
 */

// The app's theme, generated by tools/app.ts.
const THEME_URL = "chrome://neeko-theme/content/theme.css";
// Neeko's: the theme on Firefox's styles, in browser windows and in dialogs.
const WINDOW_SHEET = "chrome://neeko/content/neeko-theme.css";
const DIALOG_SHEET = "chrome://neeko/content/neeko-theme-dialog.css";
// Firefox's dialogs that get the theme: the prompts pages open.
const DIALOGS = new Set(["chrome://global/content/commonDialog.xhtml"]);
// On the root of every themed document.
const THEMED = "neeko-theme";

// Whether the app has a theme, found once per session: null until then.
let hasTheme = null;

function findTheme() {
  if (hasTheme === null) {
    try {
      Cc["@mozilla.org/chrome/chrome-registry;1"]
        .getService(Ci.nsIChromeRegistry)
        .convertChromeURL(Services.io.newURI(THEME_URL));
      hasTheme = true;
    } catch (e) {
      hasTheme = false;
    }
    if (hasTheme) {
      Services.obs.addObserver(onDocumentCreated, "document-element-inserted");
    }
  }
  return hasTheme;
}

function applyTheme(doc, sheet) {
  let utils = doc.defaultView.windowUtils;
  doc.documentElement.setAttribute(THEMED, "");
  for (let url of [THEME_URL, sheet]) {
    utils.loadSheetUsingURIString(url, utils.AUTHOR_SHEET);
  }
}

/**
 * Runs as each document in this process gets its root element, before its
 * first paint: Firefox's dialogs load in frames of their own.
 */
function onDocumentCreated(doc) {
  if (doc.defaultView && DIALOGS.has(doc.documentURI.split(/[?#]/)[0])) {
    applyTheme(doc, DIALOG_SHEET);
  }
}

export const NeekoTheme = {
  /**
   * Called by Firefox for each browser window, before its first layout.
   *
   * @param {Window} win
   */
  init(win) {
    if (findTheme()) {
      applyTheme(win.document, WINDOW_SHEET);
    }
  },
};
